const glyph = (font, ch) => font.glyphs[ch] || font.glyphs[String(ch).toUpperCase()] || font.glyphs[' '];

export function lineWidth(font, line) {
	let w = 0;
	[...line].forEach((ch, i) => { w += glyph(font, ch)[0].length + (i ? font.gap : 0); });
	return w;
}

// greedy word wrap to a width in tiles
export function wrap(font, text, maxW) {
	const words = String(text).split(/\s+/).filter(Boolean);
	const lines = [];
	let cur = '';
	for (const w of words) {
		const next = cur ? cur + ' ' + w : w;
		if (!cur || lineWidth(font, next) <= maxW) cur = next;
		else { lines.push(cur); cur = w; }
	}
	if (cur) lines.push(cur);
	return lines;
}

// lit font pixels as [x, y] tile positions
export function drawLines(font, lines, { x0 = 0, y0 = 0, pitch = font.height + 3, align = 'left', width = 0 } = {}) {
	const pts = [];
	lines.forEach((line, li) => {
		let x = x0 + (align === 'center' ? Math.floor((width - lineWidth(font, line)) / 2) : 0);
		const y = y0 + li * pitch;
		[...line].forEach((ch) => {
			const g = glyph(font, ch);
			g.forEach((row, ry) => {
				for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') pts.push([x + rx, y + ry]);
			});
			x += g[0].length + font.gap;
		});
	});
	return pts;
}
